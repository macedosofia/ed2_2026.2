"""Generate and verify the GlobalSIM demonstration client database."""

import argparse
import os
import random
from itertools import cycle, product
from pathlib import Path
from tempfile import TemporaryDirectory

from globalsim.models.client import validate_client
from globalsim.persistence import clients_json
from globalsim.services.clients import ClientService
from globalsim.services.packages import PackageService


DEFAULT_COUNT = 1_000
DEFAULT_SEED = 2026
DEMO_FILENAME = "clients.demo.json"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "globalsim" / "data" / DEMO_FILENAME

FIRST_NAMES = (
    "Adriana Alice Amanda Beatriz Bianca Camila Cecília Daniela Elisa Estela "
    "Gabriela Helena Isabela Júlia Luana Amaro André Bento Bruno Caio "
    "Davi Diego Enzo Felipe Heitor Hugo Luís Miguel Rafael Samuel"
).split()
SURNAMES = (
    "Azevedo Barreto Campos Cardoso Carvalho Coelho Cunha Duarte Farias "
    "Freitas Garcia Lemos Lima Matos Medeiros Monteiro Moura Nogueira "
    "Pacheco Ribeiro Rocha Sampaio Teixeira Viana Vieira"
).split()


def validate_clients(records):
    """Normalize records with the client model and reject repeated IDs."""
    clients = []
    ids = set()
    for record in records:
        client = validate_client(record)
        client_id = client["id"]
        if client_id in ids:
            raise ValueError(f"ID de cliente duplicado ({client_id}).")
        ids.add(client_id)
        clients.append(client)
    return clients


def generate_clients(count=DEFAULT_COUNT, seed=DEFAULT_SEED):
    """Return validated clients in a reproducibly shuffled insertion order."""
    if type(count) is not int or count <= 0:
        raise ValueError("A quantidade deve ser um inteiro positivo.")
    if type(seed) is not int:
        raise ValueError("A semente deve ser um inteiro.")

    package_codes = [package["codigo"] for package in PackageService().list_all()]
    packages = cycle(package_codes or [None])
    records = []
    for client_id, name in enumerate(_demo_names(count), start=1):
        has_esim = client_id % 5 != 0
        records.append({
            "id": client_id,
            "nome": name,
            "email": f"cliente{client_id:04d}@example.test",
            "esim": f"ESIM-{client_id:05d}" if has_esim else None,
            "pacote": next(packages) if has_esim else None,
            "status": "inativo" if client_id % 7 == 0 else "ativo",
        })

    clients = validate_clients(records)
    random.Random(seed).shuffle(clients)
    return clients


def _demo_names(count):
    names = list(DEMO_NAMES[:count])
    existing_names = {name.casefold() for name in names}
    for first_name, surname in product(FIRST_NAMES, SURNAMES):
        if len(names) == count:
            break
        name = f"{first_name} {surname}"
        if name.casefold() not in existing_names:
            names.append(name)
    names.extend(f"Cliente {index:04d}" for index in range(len(names) + 1, count + 1))
    return names


def generate_demo(path=DEFAULT_OUTPUT, *, count=DEFAULT_COUNT, seed=DEFAULT_SEED, replace=False):
    """Validate a staged database with ClientService before publishing it."""
    path = Path(path)
    if path.name != DEMO_FILENAME:
        raise ValueError(f"O arquivo de saída deve se chamar {DEMO_FILENAME}.")
    if path.is_symlink():
        raise ValueError("O caminho de saída deve apontar para um arquivo próprio.")
    if path.exists() and not replace:
        raise FileExistsError(f"{path} já existe. Use --replace para substituir a base demonstrativa.")

    clients = generate_clients(count, seed)
    path.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(dir=path.parent) as directory:
        staged_path = Path(directory) / DEMO_FILENAME
        clients_json.save(staged_path, clients)
        stats = ClientService(staged_path).statistics()
        if stats["size"] != count:
            raise ValueError("A quantidade de clientes carregados difere da quantidade solicitada.")

        if replace:
            staged_path.replace(path)
        else:
            # A link publishes the complete file only if the destination is still free.
            os.link(staged_path, path)
    return stats


def main(argv=None):
    parser = argparse.ArgumentParser(description="Gera e verifica a base demonstrativa de clientes.")
    parser.add_argument("--count", type=int, default=DEFAULT_COUNT, help="quantidade de clientes")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="semente do embaralhamento")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="caminho de clients.demo.json")
    parser.add_argument("--replace", action="store_true", help="substitui explicitamente a base demonstrativa")
    args = parser.parse_args(argv)
    try:
        stats = generate_demo(args.output, count=args.count, seed=args.seed, replace=args.replace)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    print(f"Base gravada em {args.output}")
    print(" | ".join(f"{key}={value}" for key, value in stats.items()))


